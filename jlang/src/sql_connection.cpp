// DataSource (GenericObjectPool + PoolableConnectionFactory + PoolingDataSource)
DataSource::DataSource(const String& url, const String& user, const String& password)
    : url_(url), user_(user), password_(password) {
    config_ = Config::parse(url, user, password);
}

Session* DataSource::createSession() {
    auto* s = new Session(config_);
    s->connect();
    return s;
}

void DataSource::destroySession(Session* s) noexcept {
    if (s != nullptr) s->close();
}

Connection* DataSource::getConnection() {
    const int64_t start = nowMillis();
    for (;;) {
        Session* s = nullptr;
        bool created = false;
        int64_t validationIdle = -1;
        bool defaultAutoCommit = true, defaultReadOnly = false;
        JSYNC(this) {
            validationIdle = validationIdleMillis_;
            defaultAutoCommit = defaultAutoCommit_;
            defaultReadOnly = defaultReadOnly_;
            for (;;) {
                if (closed_) throw IllegalStateException(String("Pool not open"));
                if (!idle_.empty()) {
                    s = idle_.front();
                    idle_.pop_front();
                    numActive_++;
                    break;
                }
                if (maxActive_ < 0 || numActive_ < maxActive_ || whenExhausted_ == WHEN_EXHAUSTED_GROW) {
                    numActive_++;
                    created = true;
                    break;
                }
                if (whenExhausted_ == WHEN_EXHAUSTED_FAIL) {
                    throw SQLException(String("Cannot get a connection, pool error Pool exhausted"));
                }
                try {
                    if (maxWait_ < 0) {
                        wait();
                    } else {
                        int64_t remaining = maxWait_ - (nowMillis() - start);
                        if (remaining <= 0) {
                            throw SQLException(String("Cannot get a connection, pool error Timeout waiting for idle object"));
                        }
                        wait(remaining);
                    }
                } catch (InterruptedException& e) {
                    sync::interrupt(sync::current());  // Thread.currentThread().interrupt()
                    throw SQLException(String("Cannot get a connection, general error"), e);
                }
            }
        }
        auto release = [this]() noexcept {
            JSYNC(this) {
                numActive_--;
                notifyAll();
            }
        };
        if (created) {
            try {
                s = createSession();
            } catch (...) {
                release();
                throw;
            }
        } else if (validationIdle >= 0 && nowMillis() - s->lastUsedMillis.load() > validationIdle && !s->ping(1)) {
            // jlang addition: drop sessions the server closed while they were idle.
            destroySession(s);
            release();
            continue;
        }
        // PoolableConnectionFactory.activateObject
        try {
            if (s->autoCommit != defaultAutoCommit) {
                std::lock_guard<std::recursive_mutex> lk(s->mu);
                s->autoCommit = defaultAutoCommit;
                s->executeSimple(defaultAutoCommit ? "SET autocommit=1" : "SET autocommit=0");
            }
            s->readOnly = defaultReadOnly;
        } catch (SQLException& e) {
            destroySession(s);
            release();
            if (created) {
                throw SQLException(str("Cannot get a connection, pool error Could not create a validated object, cause: ",
                                       e.getMessage()));
            }
            continue;
        }
        return new Connection(s, this);
    }
}

Connection* DataSource::getConnection(const String& user, const String& password) {
    (void)user;
    (void)password;
    throw UnsupportedOperationException(String());
}

void DataSource::returnSession(Session* s) noexcept {
    bool destroy = false;
    try {
        if (s->isClosed()) {
            destroy = true;  // dbcp: invalidateObject
        } else {
            // PoolableConnectionFactory.passivateObject
            std::lock_guard<std::recursive_mutex> lk(s->mu);
            if (!s->autoCommit && !s->readOnly) s->executeSimple("rollback");
            if (!s->autoCommit) {
                s->autoCommit = true;
                s->executeSimple("SET autocommit=1");
            }
        }
    } catch (...) {
        destroy = true;
    }
    try {
        JSYNC(this) {
            if (!destroy && (closed_ || (maxIdle_ >= 0 && static_cast<int32_t>(idle_.size()) >= maxIdle_))) {
                destroy = true;
            }
            if (!destroy) {
                s->lastUsedMillis = nowMillis();
                idle_.push_front(s);  // LIFO
            }
            numActive_--;
            notifyAll();
        }
    } catch (...) {
        destroy = true;
    }
    if (destroy) destroySession(s);
}

