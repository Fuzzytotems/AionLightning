// Connector/J MysqlSavepoint.
class MysqlSavepoint final : public Savepoint {
public:
    explicit MysqlSavepoint(const String& name) : name_(name) {}
    int32_t getSavepointId() override {
        throw SQLException(String("Only named savepoints are supported."), String("S1C00"));
    }
    String getSavepointName() override { return name_; }

private:
    String name_;
};

// Connector/J MysqlSavepoint.getUniqueId(): java.rmi.server.UID text with ':' and '-' -> '_'.
String uniqueSavepointName() {
    static std::atomic<int32_t> counter{-32768};
    static const int64_t unique = nowMillis() ^ (reinterpret_cast<intptr_t>(&counter) >> 4);
    char buf[80];
    std::snprintf(buf, sizeof buf, "_%x_%llx_%x", static_cast<unsigned>(unique & 0x7fffffff),
                  static_cast<unsigned long long>(nowMillis()), static_cast<unsigned>(counter.fetch_add(1) & 0xffff));
    return String(buf);
}

std::string quoteIdentifier(const String& name) {
    std::string r = "`";
    for (char c : std::string_view(name)) {
        if (c == '`') r += '`';
        r += c;
    }
    r += '`';
    return r;
}

