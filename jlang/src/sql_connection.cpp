Connection* DriverManager::getConnection(const String& url, const String& user, const String& password) {
    Config* cfg = Config::parse(url, user, password);
    if (cfg->connectTimeoutMs == 0 && g_loginTimeout.load() > 0) {
        cfg->connectTimeoutMs = static_cast<uint32_t>(g_loginTimeout.load()) * 1000u;
    }
    auto* s = new Session(cfg);
    s->connect();
    return new Connection(s, nullptr);
}

Connection* DriverManager::getConnection(const String& url) {
    return getConnection(url, String(), String());
}

void DriverManager::setLoginTimeout(int32_t seconds) {
    g_loginTimeout.store(seconds);
}

int32_t DriverManager::getLoginTimeout() {
    return g_loginTimeout.load();
}

