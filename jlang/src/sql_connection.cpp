Connection::Connection(Session* session, DataSource* pool) : session_(session), pool_(pool) {}

void Connection::throwClosed() {
    if (pool_ != nullptr) throw SQLException(String("Connection is closed."));
    throwSql("No operations allowed after connection closed.", "08003");
}

Session* Connection::session() {
    if (closed_ || session_ == nullptr) throwClosed();
    return session_;
}

String Connection::getURL() {
    return session_ != nullptr ? session_->cfg->url : String();
}

void Connection::registerStatement(Statement* s) {
    statements_.push_back(s);
}

void Connection::unregisterStatement(Statement* s) noexcept {
    for (size_t i = statements_.size(); i > 0; i--) {
        if (statements_[i - 1] == s) {
            statements_.erase(statements_.begin() + static_cast<std::ptrdiff_t>(i - 1));
            return;
        }
    }
}

Statement* Connection::createStatement() {
    return createStatement(ResultSet::TYPE_FORWARD_ONLY, ResultSet::CONCUR_READ_ONLY);
}

Statement* Connection::createStatement(int32_t resultSetType, int32_t resultSetConcurrency) {
    (void)session();
    auto* s = new Statement(this, resultSetType, resultSetConcurrency);
    registerStatement(s);
    return s;
}

PreparedStatement* Connection::prepareStatement(const String& sql) {
    return prepareStatement(sql, ResultSet::TYPE_FORWARD_ONLY, ResultSet::CONCUR_READ_ONLY);
}

PreparedStatement* Connection::prepareStatement(const String& sql, int32_t autoGeneratedKeys) {
    PreparedStatement* ps = prepareStatement(sql);
    if (autoGeneratedKeys == Statement::RETURN_GENERATED_KEYS) ps->setRetrieveGeneratedKeys(true);
    return ps;
}

PreparedStatement* Connection::prepareStatement(const String& sql, int32_t resultSetType, int32_t resultSetConcurrency) {
    (void)session();
    auto* ps = new PreparedStatement(this, sql, resultSetType, resultSetConcurrency);
    registerStatement(ps);
    return ps;
}

CallableStatement* Connection::prepareCall(const String& sql) {
    return prepareCall(sql, ResultSet::TYPE_FORWARD_ONLY, ResultSet::CONCUR_READ_ONLY);
}

CallableStatement* Connection::prepareCall(const String& sql, int32_t resultSetType, int32_t resultSetConcurrency) {
    (void)session();
    auto* cs = new CallableStatement(this, sql, resultSetType, resultSetConcurrency);
    registerStatement(cs);
    return cs;
}

void Connection::setAutoCommit(bool autoCommit) {
    Session* s = session();
    std::lock_guard<std::recursive_mutex> lk(s->mu);
    s->autoCommit = autoCommit;
    s->executeSimple(autoCommit ? "SET autocommit=1" : "SET autocommit=0");
}

bool Connection::getAutoCommit() {
    return session()->autoCommit;
}

void Connection::commit() {
    Session* s = session();
    if (s->autoCommit) throw SQLException(String("Can't call commit when autocommit=true"));
    try {
        s->executeSimple("commit");
    } catch (SQLException& e) {
        if (e.getSQLState().equals("08S01")) {
            throwSql("Communications link failure during commit(). Transaction resolution unknown.", "08007");
        }
        throw;
    }
}

void Connection::rollback() {
    Session* s = session();
    if (s->autoCommit) throwSql("Can't call rollback when autocommit=true", "08003");
    try {
        s->executeSimple("rollback");
    } catch (SQLException& e) {
        if (e.getSQLState().equals("08S01")) {
            throwSql("Communications link failure during rollback(). Transaction resolution unknown.", "08007");
        }
        throw;
    }
}

void Connection::rollback(Savepoint* savepoint) {
    Session* s = session();
    if (savepoint == nullptr) throw NullPointerException();
    try {
        s->executeSimple(str("ROLLBACK TO SAVEPOINT ", quoteIdentifier(savepoint->getSavepointName())));
    } catch (SQLException& e) {
        if (e.getSQLState().equals("08S01")) {
            throwSql("Communications link failure during rollback(). Transaction resolution unknown.", "08007");
        }
        throw;
    }
}

Savepoint* Connection::setSavepoint() {
    return setSavepoint(uniqueSavepointName());
}

Savepoint* Connection::setSavepoint(const String& name) {
    if (name.isNull() || name.length() == 0) throwSql("Savepoint name can not be NULL or empty", "S1009");
    Session* s = session();
    auto* sp = new MysqlSavepoint(name);
    s->executeSimple(str("SAVEPOINT ", quoteIdentifier(name)));
    return sp;
}

void Connection::releaseSavepoint(Savepoint* savepoint) {
    (void)savepoint;  // Connector/J 5.1: no-op
}

void Connection::setReadOnly(bool readOnly) {
    session()->readOnly = readOnly;
}

bool Connection::isReadOnly() {
    return session()->readOnly;
}

void Connection::setTransactionIsolation(int32_t level) {
    Session* s = session();
    const char* sql = nullptr;
    switch (level) {
        case TRANSACTION_NONE: throwSql("Transaction isolation level NONE not supported by MySQL", "S1C00");
        case TRANSACTION_READ_COMMITTED: sql = "SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED"; break;
        case TRANSACTION_READ_UNCOMMITTED: sql = "SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED"; break;
        case TRANSACTION_REPEATABLE_READ: sql = "SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ"; break;
        case TRANSACTION_SERIALIZABLE: sql = "SET SESSION TRANSACTION ISOLATION LEVEL SERIALIZABLE"; break;
        default: throwSql(str("Unsupported transaction isolation level '", level, "'"), "S1C00");
    }
    s->executeSimple(sql);
}

int32_t Connection::getTransactionIsolation() {
    Session* s = session();
    ExecResult* r;
    try {
        r = s->execute("SELECT @@session.transaction_isolation");
    } catch (SQLException& e) {
        if (e.getSQLState().equals("08S01")) throw;
        r = s->execute("SELECT @@session.tx_isolation");
    }
    if (r->rows == nullptr || r->rows->nrows == 0 || r->rows->lens[0] < 0) {
        throwSql("Could not retrieve transaction isolation level from server", "S1000");
    }
    std::string_view v(r->rows->data + r->rows->offs[0], static_cast<size_t>(r->rows->lens[0]));
    if (v == "READ-UNCOMMITTED") return TRANSACTION_READ_UNCOMMITTED;
    if (v == "READ-COMMITTED") return TRANSACTION_READ_COMMITTED;
    if (v == "REPEATABLE-READ") return TRANSACTION_REPEATABLE_READ;
    if (v == "SERIALIZABLE") return TRANSACTION_SERIALIZABLE;
    throwSql(str("Could not map transaction isolation '", std::string(v), " to a valid JDBC level."), "S1000");
}

void Connection::setCatalog(const String& catalog) {
    Session* s = session();
    if (catalog.isNull()) throwSql("Catalog can not be null", "S1009");
    s->executeSimple(str("USE ", quoteIdentifier(catalog)));
    s->catalog = catalog;
}

String Connection::getCatalog() {
    return String(session()->catalog);
}

DatabaseMetaData* Connection::getMetaData() {
    (void)session();
    return new DatabaseMetaData(this);
}

void Connection::close() noexcept {
    if (closed_) return;
    closed_ = true;
    try {
        std::vector<Statement*> open;
        open.swap(statements_);
        for (Statement* st : open) st->closeFromConnection();
    } catch (...) {
    }
    Session* s = session_;
    session_ = nullptr;
    if (s == nullptr) return;
    if (pool_ != nullptr) {
        pool_->returnSession(s);
    } else {
        s->close();
    }
}

bool Connection::isClosed() noexcept {
    return closed_ || session_ == nullptr || session_->isClosed();
}

bool Connection::isValid(int32_t timeoutSeconds) {
    if (isClosed()) return false;
    if (session_->ping(timeoutSeconds < 0 ? 0 : timeoutSeconds)) return true;
    session_->close();  // Connector/J abortInternal()
    return false;
}

