void DataSource::preparePool() {
    for (;;) {
        JSYNC(this) {
            if (closed_) throw IllegalStateException(String("Pool not open"));
            int32_t deficit = minIdle_ - static_cast<int32_t>(idle_.size());
            if (maxActive_ >= 0) {
                int32_t growLimit = maxActive_ - numActive_ - static_cast<int32_t>(idle_.size());
                if (growLimit < deficit) deficit = growLimit;
            }
            if (deficit <= 0) return;
        }
        Session* s = createSession();
        bool destroy = false;
        JSYNC(this) {
            if (closed_ || (maxIdle_ >= 0 && static_cast<int32_t>(idle_.size()) >= maxIdle_)) {
                destroy = true;
            } else {
                idle_.push_front(s);
                notifyAll();
            }
        }
        if (destroy) {
            destroySession(s);
            return;
        }
    }
}

void DataSource::close() noexcept {
    std::deque<Session*> toClose;
    JSYNC(this) {
        closed_ = true;
        toClose.swap(idle_);
        notifyAll();
    }
    for (Session* s : toClose) destroySession(s);
}

bool DataSource::isClosed() {
    JSYNC(this) { return closed_; }
    return true;
}

